import { build } from "esbuild";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const runtimeDirectory = dirname(fileURLToPath(import.meta.url));
const landingDirectory = resolve(runtimeDirectory, "../../skriftapp/buildapp/landing");
const outputDirectory = resolve(landingDirectory, "vendor");
const outputFile = resolve(outputDirectory, "three-device-runtime.js");
const threeLicense = resolve(runtimeDirectory, "node_modules/three/LICENSE");

await mkdir(outputDirectory, { recursive: true });
await build({
  entryPoints: [resolve(runtimeDirectory, "three-device-entry.js")],
  outfile: outputFile,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  minify: true,
  legalComments: "none",
  sourcemap: false,
  logLevel: "info",
});

// Three.js shader templates retain trailing blanks after minification.
// Normalize those insignificant blanks so generated assets pass diff checks.
const bundledSource = await readFile(outputFile, "utf8");
await writeFile(outputFile, bundledSource.replace(/[\t ]+$/gm, ""), "utf8");

const packageDetails = JSON.parse(
  await readFile(resolve(runtimeDirectory, "node_modules/three/package.json"), "utf8"),
);
await copyFile(threeLicense, resolve(outputDirectory, "THREE-LICENSE.txt"));
await writeFile(
  resolve(outputDirectory, "README.md"),
  `# Three.js device runtime\n\nGenerated by \`npm run build\` in \`design/landing-runtime\` from Three.js ${packageDetails.version}. Do not edit the bundle by hand. The adjacent license applies to the vendored Three.js code.\n`,
  "utf8",
);
