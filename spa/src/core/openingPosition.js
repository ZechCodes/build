// A visit owns its opening position even when it reuses a mounted scroller.
// Pair it with paintKeepingPlace and followConversation, which supplies the
// placement callback through onLand.
export const OPENING_READ_WAIT_MS = 5000;
const targetArrived = (hasItems, held, next, wasAwaiting, awaiting) =>
  hasItems && ((next !== null && held !== next) || (wasAwaiting && !awaiting));
const TAKEOVER_KEYS = new Set(["ArrowUp", "ArrowDown", "PageUp", "PageDown", "Home", "End", " ", "Enter"]);

export function createOpeningPosition(resumeReporting, repaint = () => {}) {
  let body = null;
  let generation = 0;
  let first = true;
  let target;
  let expectedTop = null;
  let abandoned = false;
  let expired = false;
  let awaiting = true;
  let framePending = false;
  let timer = null;
  let disposed = false;
  let resolved = false;
  let place = null;
  let content = null;
  let resizeObserver = null;
  const waiting = () => !expired && !abandoned && !resolved && (awaiting || framePending);
  const stopWatchingLayout = () => {
    resizeObserver?.disconnect();
    resizeObserver = null;
    content = null;
    place = null;
  };
  const abandon = () => {
    abandoned = true;
    framePending = false;
    clearTimeout(timer);
    timer = null;
    stopWatchingLayout();
  };
  const takeOver = () => {
    if (abandoned) return;
    abandon();
    resumeReporting(body);
  };
  const input = (event) => {
    if (event.type === "keydown" && !TAKEOVER_KEYS.has(event.key)) return;
    takeOver();
  };
  const moved = () => {
    if (expectedTop === null || Math.abs(body.scrollTop - expectedTop) < 1) return false;
    // Layout can reduce the scroll range and clamp the last write on its own.
    const maximum = Math.max(0, body.scrollHeight - body.clientHeight);
    return Math.abs(body.scrollTop - Math.min(expectedTop, maximum)) >= 1;
  };
  const scroll = () => {
    if (!abandoned && moved()) takeOver();
  };
  // Release the position before controls change the view, including clicks
  // generated by assistive technology or stopped by a control's handler.
  const events = ["wheel", "touchstart", "pointerdown", "keydown", "click"];
  const inputOptions = { capture: true, passive: true };
  const unbind = () => {
    if (!body) return;
    for (const type of events) body.removeEventListener(type, input, inputOptions);
    body.removeEventListener("scroll", scroll);
  };
  const reset = () => {
    generation += 1;
    stopWatchingLayout();
    clearTimeout(timer);
    timer = null;
    first = true;
    resolved = false;
    target = undefined;
    expectedTop = null;
    abandoned = false;
    expired = false;
    awaiting = true;
    framePending = false;
  };
  const bind = (scroller) => {
    if (body === scroller) return;
    unbind();
    body = scroller;
    reset();
    for (const type of events) body.addEventListener(type, input, inputOptions);
    body.addEventListener("scroll", scroll, { passive: true });
  };
  const restore = () => {
    if (place && !place()) stopWatchingLayout();
    expectedTop = body.scrollTop;
  };
  const watchLayout = () => {
    if (resizeObserver || abandoned || typeof ResizeObserver !== "function") return;
    if (resolved && !place) return;
    let visible = body.clientHeight > 0;
    resizeObserver = new ResizeObserver(() => {
      const hadViewport = visible;
      visible = body.clientHeight > 0;
      if (!visible || abandoned || disposed) return;
      if (moved()) {
        takeOver();
      } else if (!hadViewport && !resolved) {
        first = true;
        repaint();
      } else {
        restore();
      }
    });
    // Content height catches media and code expansion. The scroller's content
    // box also changes when its viewport or padding changes.
    resizeObserver.observe(body);
  };
  const startWait = () => {
    if (timer !== null || expired || abandoned || resolved) return;
    timer = setTimeout(() => {
      timer = null;
      expired = true;
      resumeReporting(body);
    }, OPENING_READ_WAIT_MS);
  };
  return {
    reset,
    waiting,
    active: () => !abandoned && !resolved && !disposed,
    painted(timeline = null) {
      if (!body || abandoned) return;
      if (timeline !== content && resizeObserver) {
        if (content) resizeObserver.unobserve(content);
        content = timeline;
        if (content) resizeObserver.observe(content);
      }
      restore();
    },
    prepare(scroller, { hasItems, target: nextTarget, waitingForHistory }) {
      bind(scroller);
      if (moved()) abandon();
      watchLayout();
      startWait();
      const wasAwaiting = awaiting;
      awaiting = waitingForHistory || body.clientHeight <= 0;
      const changedTarget = targetArrived(hasItems, target, nextTarget, wasAwaiting, awaiting);
      const opening = !abandoned && !resolved && (first || changedTarget);
      if (hasItems) {
        first = false;
        target = nextTarget;
      }
      if (opening) generation += 1;
      const ticket = generation;
      return {
        opening,
        canLand: () => {
          if (disposed || abandoned || generation !== ticket) return false;
          if (moved()) takeOver();
          return !abandoned;
        },
        onLand: (settled, position) => {
          if (disposed || generation !== ticket) return;
          place = position;
          expectedTop = body.scrollTop;
          framePending = !settled;
          if (settled && hasItems && !awaiting) {
            resolved = true;
            clearTimeout(timer);
            timer = null;
          }
          if (settled && !waiting()) resumeReporting(body);
        },
      };
    },
    dispose() {
      disposed = true;
      reset();
      unbind();
    },
  };
}
